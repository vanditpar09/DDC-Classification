    await page.locator('#photo-tab').click();
    await page.locator('#open-camera').click();
    await page.waitForFunction(()=>cameraStream&&document.getElementById('camera-video').videoWidth>0);
    await page.evaluate(()=>window.testTracks=cameraStream.getTracks());
    await page.locator('#take-photo').click();
    await page.waitForFunction(()=>previewBlob!==null&&cameraStream===null);
    assert(await page.evaluate(()=>testTracks.every(track=>track.readyState==='ended')));
    await page.screenshot({path:path.join(output,'mobile-camera.png'),fullPage:true});
    await page.locator('#retake-photo').click();
    await page.waitForFunction(()=>cameraStream!==null);
    await page.evaluate(()=>window.testTracks=cameraStream.getTracks());
    await page.locator('#close-camera').click();
    assert(await page.evaluate(()=>testTracks.every(track=>track.readyState==='ended')));
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    check('mobile camera preview, retake, stop tracks and no horizontal overflow');
    await page.evaluate(()=>{navigator.mediaDevices.getUserMedia=()=>Promise.reject(new DOMException('Denied','NotAllowedError'));});
