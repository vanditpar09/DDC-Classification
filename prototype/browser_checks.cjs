    assert.equal(first.decision.action,'request_page');
    check('real OCR repair and all three DDC levels with conservative review');
    await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
    await page.reload();await idle();assert.equal((await state()).id,first.id);
    assert.equal((await state()).work.ocr_passes,first.work.ocr_passes);
    check('reload restores book without repeating inference');
