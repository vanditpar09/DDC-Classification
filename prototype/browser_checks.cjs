    assert(await page.locator('#camera-file').count());
    check('camera permission denial provides a photo-picker fallback');
    const keys=await page.evaluate(async()=>{
      const names=await caches.keys(), urls=[];
      for(const name of names)for(const request of await(await caches.open(name)).keys())urls.push(new URL(request.url).pathname);
      return urls;
    });
    assert(!keys.some(key=>key.startsWith('/api/')));
